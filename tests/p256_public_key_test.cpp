#include <array>
#include <cassert>
#include <cstdint>

#include "m5auth/session/session.hpp"

namespace {

m5auth::session::P256PublicKey valid_generator() {
    return {
        0x04,
        0x6b,0x17,0xd1,0xf2,0xe1,0x2c,0x42,0x47,0xf8,0xbc,0xe6,0xe5,0x63,0xa4,0x40,0xf2,
        0x77,0x03,0x7d,0x81,0x2d,0xeb,0x33,0xa0,0xf4,0xa1,0x39,0x45,0xd8,0x98,0xc2,0x96,
        0x4f,0xe3,0x42,0xe2,0xfe,0x1a,0x7f,0x9b,0x8e,0xe7,0xeb,0x4a,0x7c,0x0f,0x9e,0x16,
        0x2b,0xce,0x33,0x57,0x6b,0x31,0x5e,0xce,0xcb,0xb6,0x40,0x68,0x37,0xbf,0x51,0xf5,
    };
}

}  // namespace

int main() {
    using namespace m5auth::session;

    const P256PublicKey valid = valid_generator();
    assert(valid_p256_public_key(valid));

    P256PublicKey off_curve{};
    off_curve.fill(0x01);
    off_curve[0] = 0x04;
    assert(!valid_p256_public_key(off_curve));

    P256PublicKey wrong_prefix = valid;
    wrong_prefix[0] = 0x02;
    assert(!valid_p256_public_key(wrong_prefix));

    const std::array<std::uint8_t, 64> short_key{};
    assert(!valid_p256_public_key(short_key));
    return 0;
}
